/* system-fetch.js — the OS UI's fetches are rate-limit-trusted, not throttled.
 *
 * Why this exists: the server's global /api/ limiter (server/middleware.js)
 * keys on client IP with a 15-minute window. The whole desktop shares one
 * IP (localhost), so unsigned OS-UI traffic — the default launcher, shell,
 * Settings, the app manager — competes for the same 100-request budget as
 * everything else and can end up 429'd ("Too many requests from this IP")
 * for a quarter of an hour after a few app launches. The OS UI is the
 * trusted side: it runs in the NW.js host page with Node integration and
 * already holds the per-launch secret (ASTROOS_SYSTEM_API_RATE_LIMIT_SECRET,
 * generated by scripts/startup.js), the same secret the sandbox bridge
 * uses for system-app proxies (app-sandbox.js systemAppRateLimitHeaders).
 * Signing its requests moves them out of the untrusted bucket, exactly
 * like server-side isTrustedSystemAppRequest() intends.
 *
 * What is NOT signed (and stays rate-limited): sandboxed third-party apps'
 * direct server calls, and any external client — by design.
 *
 * The wrapper is defensive by contract: it never throws, never touches
 * cross-origin or non-/api/ requests, never overwrites caller-supplied
 * headers, and degrades to plain fetch when Node integration or the
 * secret is unavailable.
 */
(function () {
  'use strict';
  if (typeof window === 'undefined' || typeof window.fetch !== 'function') return;
  if (window.__novaSystemFetchInstalled) return;
  window.__novaSystemFetchInstalled = true;

  /* Identifier stamped into X-Nova-System-App for audit visibility on the
     server. The validator only checks presence + HMAC, so this is a label,
     not an authorization decision. */
  var SYSTEM_APP_ID = 'com.astroos.os-shell';

  function computeTrustHeaders() {
    try {
      if (typeof require !== 'function' || typeof process === 'undefined') return null;
      var secret = process.env.ASTROOS_SYSTEM_API_RATE_LIMIT_SECRET;
      if (!secret) return null;
      var timestamp = String(Date.now());
      var signature = require('crypto')
        .createHmac('sha256', secret)
        .update(timestamp + '\n' + SYSTEM_APP_ID)
        .digest('hex');
      return {
        'X-Nova-System-App': SYSTEM_APP_ID,
        'X-Nova-System-Time': timestamp,
        'X-Nova-System-Signature': signature,
      };
    } catch (_) {
      return null;
    }
  }

  function isSameOriginApiUrl(input) {
    try {
      var url = new URL(String(input), window.location.href);
      return url.origin === window.location.origin && url.pathname.startsWith('/api/');
    } catch (_) {
      return false;
    }
  }

  var originalFetch = window.fetch;
  var boundOriginalFetch = typeof originalFetch === 'function' ? originalFetch.bind(window) : null;
  if (!boundOriginalFetch) return;

  window.fetch = function (input, init) {
    try {
      /* Only plain string/URL inputs are signed. Request objects are passed
         through untouched — merging headers into a used Request is a spec
         minefield, and every call site in this codebase passes strings. */
      if ((typeof input === 'string' || input instanceof URL) && isSameOriginApiUrl(input)) {
        var extra = computeTrustHeaders();
        if (extra) {
          init = Object.assign({}, init);
          var headers = new Headers(init.headers || {});
          Object.keys(extra).forEach(function (name) {
            if (!headers.has(name)) headers.set(name, extra[name]);
          });
          init.headers = headers;
        }
      }
    } catch (_) {
      /* signing must never break a fetch */
    }
    return boundOriginalFetch(input, init);
  };
})();
